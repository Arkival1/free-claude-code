def science_data() -> dict[str, object]:
    """The PC Lab's tables (elements, the chemical shelf, the mixing rules'
    tables and the parts bin), for the phone's own chemistry and circuit
    benches (lab/science.js), so both give the same answers."""
    sys.path.insert(0, str(ROOT / "src"))
    from free_claude_code.studio.lab import chemicals, elements, sim, tech

    def pair(value: tuple[str, float, int] | None) -> list[object] | None:
        return list(value) if value else None

    return {
        "elements": [
            [e.symbol, e.name, e.mass, e.category, e.state, e.number]
            for e in elements.ELEMENTS
        ],
        "hazards": chemicals.HAZARDS,
        "chemicals": [
            {
                "id": c.id,
                "name": c.name,
                "formula": c.formula,
                "kind": c.kind,
                "state": c.state,
                "colour": c.colour,
                "concentration": c.concentration,
                "ions": [list(ion) for ion in c.ions],
                "acid": pair(c.acid),
                "base": pair(c.base),
                "density": c.density,
                "hazards": list(c.hazards),
                "roles": list(c.roles),
                "aliases": list(c.aliases),
                "dissolve_heat": c.dissolve_heat,
                "tags": sorted(c.tags),
                "note": c.note,
                "molar_mass": c.molar_mass,
            }
            for c in chemicals.CHEMICALS
        ],
        "solubility": sim.SOLUBILITY,
        "ion_colours": {ion: list(row) for ion, row in sim.ION_COLOURS.items()},
        "precipitates": [list(row) for row in sim.PRECIPITATES],
        "metals": {metal: list(row) for metal, row in sim.METALS.items()},
        "activity": list(sim.ACTIVITY),
        "metal_ion_names": {
            ion: list(row) for ion, row in sim._METAL_ION_NAMES.items()
        },
        "flame_colours": {
            symbol: list(row) for symbol, row in elements.FLAME_COLOURS.items()
        },
        "element_colours": chemicals._ELEMENT_COLOURS,
        "halogen_colours": chemicals._HALOGEN_COLOURS,
        "active": sorted(chemicals._ACTIVE),
        # volts_max as the bench reads it (0 means 1.3 x volts).
        "parts": [{**part.view(), "volts_max": part.volts_max} for part in tech.PARTS],
        "e12": list(tech.E12),
    }


