GODOT_TEXT = (".gd", ".gdshader", ".tscn", ".tres", ".godot", ".cfg", ".txt")


def _godot_files(folder: Path) -> dict[str, str]:
    return {
        path.relative_to(folder).as_posix(): path.read_text(encoding="utf-8")
        for path in sorted(folder.rglob("*"))
        if path.is_file() and path.suffix in GODOT_TEXT
    }


def godot_js() -> str:
    """The phone's Godot starters and FCC's probe, from studio/godot."""
    sys.path.insert(0, str(ROOT / "src"))
    from free_claude_code.studio import godot

    def starter(name: str) -> dict[str, str]:
        files: dict[str, str] = {}
        for path, data in godot.starter_files(name).items():
            if path.startswith(f"{godot.KIT_FOLDER}/"):
                continue  # the kit ships once (godot/kit.js, godot/fcc/)
            if path.endswith(".png"):
                encoded = base64.b64encode(data).decode()
                files[path] = f"data:image/png;base64,{encoded}"
            elif path.endswith(GODOT_TEXT):
                files[path] = data.decode("utf-8")
        return files

    starters = {
        name: {"about": about, "files": starter(name)}
        for name, about in PHONE_GODOT_STARTERS.items()
    }
    body = json.dumps(starters, ensure_ascii=False, indent=None, separators=(",", ":"))
    probe = json.dumps(
        _godot_files(GODOT_DIR / "probe"), ensure_ascii=False, separators=(",", ":")
    )
    return f"""// Generated by scripts/phone/build_pages.py from studio/godot (starters/
// and probe/). Do not edit by hand. The games the phone's Godot player starts
// from, and the probe that tests what Godot can do on the phone.
export const GODOT_STARTERS = {body};
export const GODOT_PROBE = {probe};
"""


KIT_JS = SOURCE / "godot" / "kit.js"
KIT_FONTS = SOURCE / "godot" / "fcc" / "fonts"
"""FCC's Godot kit on the phone: its scripts in godot/kit.js, its fonts (big,
fetched when a game first uses the kit and kept, checksum-checked) in
godot/fcc/fonts/. Both copied from studio/godot/kit."""


def kit_js() -> str:
    """The phone's copy of FCC's Godot kit: its scripts, and the checksums of
    its fonts (copied beside it by copy_kit_fonts)."""
    import hashlib

    kit = GODOT_DIR / "kit"
    text: dict[str, str] = {}
    fonts: list[list[str]] = []
    for path in sorted(kit.rglob("*")):
        if not path.is_file() or path.name.startswith("."):
            continue
        name = path.relative_to(kit).as_posix()
        if path.suffix == ".ttf":
            digest = hashlib.sha256(path.read_bytes()).hexdigest()
            fonts.append([f"godot/fcc/{name}", digest])
        elif path.suffix != ".txt":
            text[name] = path.read_text(encoding="utf-8")
    body = json.dumps(text, ensure_ascii=False, separators=(",", ":"))
    return f"""// Generated by scripts/phone/build_pages.py from studio/godot/kit. Do not
// edit by hand. FCC's Godot kit (res://fcc/ in a game): its scripts here, its
// fonts (SIL OFL, godot/fcc/fonts/OFL.txt) fetched when a game uses the kit.
export const KIT_TEXT = {body};
export const KIT_FONTS = {json.dumps(fonts)};
"""


def copy_kit_fonts() -> None:
    """The kit's fonts and their licence, into the phone app."""
    if KIT_FONTS.exists():
        shutil.rmtree(KIT_FONTS)
    KIT_FONTS.mkdir(parents=True)
    for path in sorted((GODOT_DIR / "kit" / "fonts").iterdir()):
        if path.suffix in (".ttf", ".txt"):
            shutil.copyfile(path, KIT_FONTS / path.name)


BUILTIN_SKILLS = ROOT / "src" / "free_claude_code" / "studio" / "builtin_skills"
