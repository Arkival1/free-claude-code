_TUTORIAL = re.compile(r"^\* \[\*\*([^*]+)\*\*: _(.+?)_\]\((\S+?)\)\s*(\[video\])?\s*$")


def tutorial_rows(readme: str) -> list[list[str]]:
    """build-your-own-x's tutorials: [topic, language, title, link, "video"
    for a video course or ""]."""
    rows: list[list[str]] = []
    topic = ""
    for line in readme.splitlines():
        if line.startswith("#### "):
            heading = line[5:].strip()
            topic = heading.split("`")[1] if "`" in heading else heading
            continue
        if line.startswith("## ") and topic:
            break
        found = _TUTORIAL.match(line.strip())
        if topic and found:
            language, title, link, video = found.groups()
            rows.append(
                [topic, language.strip(), title.strip(), link, "video" if video else ""]
            )
    return rows


def tutorials_js() -> str:
    """The phone Lab's Library room: build-your-own-x (CC0, vendored)."""
    with zipfile.ZipFile(BUILD_YOUR_OWN_X) as bundle:
        name = next(n for n in bundle.namelist() if n.endswith("/README.md"))
        readme = bundle.read(name).decode("utf-8")
    body = json.dumps(tutorial_rows(readme), ensure_ascii=False, separators=(",", ":"))
    return f"""// Generated by scripts/phone/build_pages.py from codecrafters-io/build-your-own-x
// (CC0, vendor/repos): step-by-step tutorials for building technologies from
// scratch. Do not edit by hand. Each row: topic, language, title, link, and
// "video" for a video course.
export const TUTORIALS = {body};
"""


