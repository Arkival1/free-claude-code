TEMPLATES_JS = SOURCE / "js" / "templates.js"
WEB_TEMPLATES = ("business", "website", "landing", "webapp", "game")
"""The starters that run in a browser, so the phone can preview them."""
TITLE_MARK = "FCCTITLE0"
""" Stands in for the title; its lower case stands in for the slug."""
INITIAL_MARK = "FCCINITIAL0"
"""Stands in for the first letter of the title (the business site's icon)."""
INDEX = """<!doctype html>
<meta charset="utf-8" />
<meta http-equiv="refresh" content="0; url=phone/" />
<title>FCC Phone</title>
<a href="phone/">Open FCC Phone</a>
"""


def templates_js() -> str:
    """The phone's templates.js, generated from the PC's starter templates."""
    sys.path.insert(0, str(ROOT / "src"))
    from free_claude_code.studio import site_layouts
    from free_claude_code.studio.templates import (
        STARTER_TEXT,
        TEMPLATES,
        template_files,
    )

    table = {
        name: {
            "about": TEMPLATES[name][0],
            "files": template_files(name, TITLE_MARK, initial=INITIAL_MARK),
        }
        for name in WEB_TEMPLATES
    }
    # FCC's own whole-site designs (plain HTML/CSS/JS, nothing from outside),
    # with the title mark where the business's name goes.
    for design in site_layouts.layouts():
        if design.source != "fcc":
            continue
        files = site_layouts.layout_files(design)
        table[design.id] = {
            "about": f"FCC design: {design.name} ({design.kind})",
            "files": {
                path: (
                    site_layouts.name_layout(body, TITLE_MARK)
                    if path.endswith(".html")
                    else body
                ).decode("utf-8")
                for path, body in files.items()
            },
        }
    body = json.dumps(table, indent=1, ensure_ascii=False)
    return f"""// Generated by scripts/phone/build_pages.py from studio/templates.py: the
// Builder's web starter projects, the same as on the PC. Do not edit by hand.
export const TEMPLATES = {body};

/** Placeholder lines in the templates, which a finished project replaces. */
export const STARTER_TEXT = {json.dumps(list(STARTER_TEXT), ensure_ascii=False)};

/** The files of one starter project, filled in with the project's title. */
export function templateFiles(name, title) {{
  const template = TEMPLATES[name];
  if (!template) throw new Error(`No template called ${{name}}. Pick one of: ${{Object.keys(TEMPLATES).join(", ")}}.`);
  const clean = String(title).replace(/[<>]/g, "");
  const slug = String(title).toLowerCase().split(/\\s+/).filter(Boolean).join("-") || "project";
  const initial = (String(title).match(/[\\p{{L}}\\p{{N}}]/u) || ["★"])[0].toUpperCase();
  const files = {{}};
  for (const [path, text] of Object.entries(template.files)) {{
    files[path] = text.replaceAll("{TITLE_MARK}", clean).replaceAll("{TITLE_MARK.lower()}", slug).replaceAll("{INITIAL_MARK}", initial);
  }}
  return files;
}}
"""


