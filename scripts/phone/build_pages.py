SKILL_CHARS = 40_000
"""The most of one skill the phone keeps (taste-skill is longer)."""


def _front(text: str) -> tuple[dict[str, str], str]:
    if not text.startswith("---"):
        return {}, text
    head, _, body = text[3:].partition("\n---")
    fields: dict[str, str] = {}
    for line in head.splitlines():
        key, sep, value = line.partition(":")
        if sep and key.strip() in {"name", "description"}:
            fields[key.strip()] = value.strip().strip('"').strip("'")
    return fields, body.lstrip("\n")


def skills_js() -> str:
    """FCC's own skills on the phone, so the skill tool works with no PC."""
    table: dict[str, dict[str, object]] = {}
    for folder in sorted(BUILTIN_SKILLS.iterdir()):
        source = folder / "SKILL.md"
        if folder.name in PC_ONLY_SKILLS or not source.is_file():
            continue
        fields, body = _front(source.read_text(encoding="utf-8"))
        name = fields.get("name") or folder.name
        files = (
            {
                path.relative_to(folder).as_posix(): path.read_text(encoding="utf-8")[
                    :SKILL_CHARS
                ]
                for path in sorted((folder / "reference").glob("*.md"))
            }
            if folder.name == "game-design"
            else {}
        )
        table[name] = {
            "about": fields.get("description", "")[:600],
            "text": body[:SKILL_CHARS],
            "files": files,
        }
    body = json.dumps(table, ensure_ascii=False, separators=(",", ":"))
    return f"""// Generated by scripts/phone/build_pages.py from studio/builtin_skills: FCC's
// own skills (each with its licence in the PC copy), so phone agents read them
// with the skill tool and no PC. Do not edit by hand.
export const SKILLS = {body};
"""


def build() -> None:
    TEMPLATES_JS.write_text(templates_js(), encoding="utf-8")
    APIS_JS.write_text(apis_js(), encoding="utf-8")
    SKILLS_JS.write_text(skills_js(), encoding="utf-8")
    SCIENCE_JS.write_text(science_js(), encoding="utf-8")
    TUTORIALS_JS.write_text(tutorials_js(), encoding="utf-8")
    GODOT_JS.write_text(godot_js(), encoding="utf-8")
    KIT_JS.write_text(kit_js(), encoding="utf-8")
    copy_kit_fonts()
    if TARGET.exists():
        shutil.rmtree(TARGET)
    shutil.copytree(SOURCE, TARGET)
    (DOCS / "index.html").write_text(INDEX, encoding="utf-8")
    # Serve the files as they are, without Jekyll.
    (DOCS / ".nojekyll").write_text("", encoding="utf-8")


if __name__ == "__main__":
    build()
    print(f"FCC Phone copied to {TARGET.relative_to(ROOT)}")
