"""Copy FCC Phone into docs/ so GitHub Pages serves it for free.

GitHub Pages publishes a branch's docs/ folder at
https://<user>.github.io/<repo>/, so the phone app ends up at .../phone/.
Run this after changing anything in src/free_claude_code/api/phone_static/;
a test fails while the two copies differ. It also writes the phone's copy of
the Builder's web starter templates from studio/templates.py and FCC's own
website designs from studio/site_layouts.
"""

import json
import re
import shutil
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "src" / "free_claude_code" / "api" / "phone_static"
DOCS = ROOT / "docs"
TARGET = DOCS / "phone"
TEMPLATES_JS = SOURCE / "js" / "templates.js"
WEB_TEMPLATES = ("business", "website", "landing", "webapp", "game")
"""The starters that run in a browser, so the phone can preview them."""
TITLE_MARK = "FCCTITLE0"
""" Stands in for the title; its lower case stands in for the slug."""
INITIAL_MARK = "FCCINITIAL0"
"""Stands in for the first letter of the title (the business site's icon)."""
INDEX = """<!doctype html>
<meta charset="utf-8" />
<meta http-equiv="refresh" content="0; url=phone/" />
<title>FCC Phone</title>
<a href="phone/">Open FCC Phone</a>
"""


def templates_js() -> str:
    """The phone's templates.js, generated from the PC's starter templates."""
    sys.path.insert(0, str(ROOT / "src"))
    from free_claude_code.studio import site_layouts
    from free_claude_code.studio.templates import (
        STARTER_TEXT,
        TEMPLATES,
        template_files,
    )

    table = {
        name: {
            "about": TEMPLATES[name][0],
            "files": template_files(name, TITLE_MARK, initial=INITIAL_MARK),
        }
        for name in WEB_TEMPLATES
    }
    # FCC's own whole-site designs (plain HTML/CSS/JS, nothing from outside),
    # with the title mark where the business's name goes.
    for design in site_layouts.layouts():
        if design.source != "fcc":
            continue
        files = site_layouts.layout_files(design)
        table[design.id] = {
            "about": f"FCC design: {design.name} ({design.kind})",
            "files": {
                path: (
                    site_layouts.name_layout(body, TITLE_MARK)
                    if path.endswith(".html")
                    else body
                ).decode("utf-8")
                for path, body in files.items()
            },
        }
    body = json.dumps(table, indent=1, ensure_ascii=False)
    return f"""// Generated by scripts/phone/build_pages.py from studio/templates.py: the
// Builder's web starter projects, the same as on the PC. Do not edit by hand.
export const TEMPLATES = {body};

/** Placeholder lines in the templates, which a finished project replaces. */
export const STARTER_TEXT = {json.dumps(list(STARTER_TEXT), ensure_ascii=False)};

/** The files of one starter project, filled in with the project's title. */
export function templateFiles(name, title) {{
  const template = TEMPLATES[name];
  if (!template) throw new Error(`No template called ${{name}}. Pick one of: ${{Object.keys(TEMPLATES).join(", ")}}.`);
  const clean = String(title).replace(/[<>]/g, "");
  const slug = String(title).toLowerCase().split(/\\s+/).filter(Boolean).join("-") || "project";
  const initial = (String(title).match(/[\\p{{L}}\\p{{N}}]/u) || ["★"])[0].toUpperCase();
  const files = {{}};
  for (const [path, text] of Object.entries(template.files)) {{
    files[path] = text.replaceAll("{TITLE_MARK}", clean).replaceAll("{TITLE_MARK.lower()}", slug).replaceAll("{INITIAL_MARK}", initial);
  }}
  return files;
}}
"""


PUBLIC_APIS = ROOT / "vendor" / "repos" / "public-apis__public-apis.zip"
APIS_JS = SOURCE / "js" / "apis.js"
_LINK = re.compile(r"\[([^\]]+)\]\(([^)\s]+)\)")


def api_rows(readme: str) -> list[list[str]]:
    """The APIs a phone can call itself: HTTPS, no key or a plain API key,
    and not marked as refusing browser calls (CORS)."""
    rows: list[list[str]] = []
    seen: set[str] = set()
    category = ""
    started = False
    for line in readme.splitlines():
        if line.startswith("### "):
            category = line[4:].strip()
            # The sponsor list and the MCP servers come first; the
            # categories start at Animals.
            started = started or category == "Animals"
            continue
        if not started or not line.startswith("| ["):
            continue
        cells = [cell.strip() for cell in line.strip().strip("|").split("|")]
        if len(cells) < 5:
            continue
        found = _LINK.match(cells[0])
        if found is None:
            continue
        name, link = found.groups()
        auth = cells[2].strip("`").strip()
        https, cors = cells[3], cells[4]
        if https != "Yes" or auth not in {"No", "apiKey"} or cors == "No":
            continue
        if name.casefold() in seen:
            # Listed under two categories: one plugin, one switch, both
            # categories and descriptions kept for the search.
            first = next(row for row in rows if row[0].casefold() == name.casefold())
            if category not in first[5]:
                first[5] = f"{first[5]}, {category}"
            if cells[1][:160] not in first[1]:
                first[1] = f"{first[1]} · {cells[1]}"[:240]
            continue
        seen.add(name.casefold())
        link = link.split("?utm_")[0]
        rows.append(
            [
                name,
                cells[1][:160],
                "key" if auth == "apiKey" else "",
                "yes" if cors == "Yes" else "",
                link,
                category,
            ]
        )
    return rows


def apis_js() -> str:
    """The phone's catalog of free APIs, from public-apis (MIT, vendored)."""
    with zipfile.ZipFile(PUBLIC_APIS) as bundle:
        name = next(
            n
            for n in bundle.namelist()
            if n.endswith("/README.md") and n.count("/") == 1
        )
        readme = bundle.read(name).decode("utf-8")
    rows = api_rows(readme)
    body = json.dumps(rows, ensure_ascii=False, separators=(",", ":"))
    return f"""// Generated by scripts/phone/build_pages.py from public-apis/public-apis
// (MIT, vendor/repos): free APIs a phone can call itself (HTTPS, no key or a
// plain API key, not marked as refusing browser calls). Do not edit by hand.
// Each row: name, what it does, "key" when it needs an API key, "yes" when
// it is known to allow browser calls, its docs link, and its category.
export const APIS = {body};
"""


BUILTIN_SKILLS = ROOT / "src" / "free_claude_code" / "studio" / "builtin_skills"
SKILLS_JS = SOURCE / "js" / "skills.js"
PC_ONLY_SKILLS = frozenset(
    {
        "add-a-library",
        "godot-dev",
        "fastapi",
        "python-testing-patterns",
        "specialist-roles",
    }
)
"""FCC skills for the PC's own work (the Changer, Godot, its Python), left
off the phone."""
SKILL_CHARS = 40_000
"""The most of one skill the phone keeps (taste-skill is longer)."""


def _front(text: str) -> tuple[dict[str, str], str]:
    if not text.startswith("---"):
        return {}, text
    head, _, body = text[3:].partition("\n---")
    fields: dict[str, str] = {}
    for line in head.splitlines():
        key, sep, value = line.partition(":")
        if sep and key.strip() in {"name", "description"}:
            fields[key.strip()] = value.strip().strip('"').strip("'")
    return fields, body.lstrip("\n")


def skills_js() -> str:
    """FCC's own skills on the phone, so the skill tool works with no PC."""
    table: dict[str, dict[str, object]] = {}
    for folder in sorted(BUILTIN_SKILLS.iterdir()):
        source = folder / "SKILL.md"
        if folder.name in PC_ONLY_SKILLS or not source.is_file():
            continue
        fields, body = _front(source.read_text(encoding="utf-8"))
        name = fields.get("name") or folder.name
        files = (
            {
                path.relative_to(folder).as_posix(): path.read_text(encoding="utf-8")[
                    :SKILL_CHARS
                ]
                for path in sorted((folder / "reference").glob("*.md"))
            }
            if folder.name == "game-design"
            else {}
        )
        table[name] = {
            "about": fields.get("description", "")[:600],
            "text": body[:SKILL_CHARS],
            "files": files,
        }
    body = json.dumps(table, ensure_ascii=False, separators=(",", ":"))
    return f"""// Generated by scripts/phone/build_pages.py from studio/builtin_skills: FCC's
// own skills (each with its licence in the PC copy), so phone agents read them
// with the skill tool and no PC. Do not edit by hand.
export const SKILLS = {body};
"""


def build() -> None:
    TEMPLATES_JS.write_text(templates_js(), encoding="utf-8")
    APIS_JS.write_text(apis_js(), encoding="utf-8")
    SKILLS_JS.write_text(skills_js(), encoding="utf-8")
    if TARGET.exists():
        shutil.rmtree(TARGET)
    shutil.copytree(SOURCE, TARGET)
    (DOCS / "index.html").write_text(INDEX, encoding="utf-8")
    # Serve the files as they are, without Jekyll.
    (DOCS / ".nojekyll").write_text("", encoding="utf-8")


if __name__ == "__main__":
    build()
    print(f"FCC Phone copied to {TARGET.relative_to(ROOT)}")
